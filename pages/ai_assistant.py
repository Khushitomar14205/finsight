import streamlit as st
from pages.common import get_context, demo_banner, get_portfolio_weights
from src.agent.tools import AgentContext
from src.agent.graph import run_agent

settings, store = get_context()
st.title("🤖 AI Research Assistant")
demo_banner(settings)
if settings.has_llm:
    st.caption(f"LLM: {settings.llm_provider} / {settings.llm_model} — used only for routing & explanation. "
               "All numbers come from deterministic Python tools.")
else:
    st.caption("No LLM key configured — running in **rule-based fallback mode**. Routing is deterministic; "
               "all analytics work identically. Add a key in `.env` to enable LLM explanations.")

st.write("Try: *\"What was the return of RELIANCE in 2023?\"* · *\"Compare the volatility of TCS and INFY\"* · "
         "*\"Show the correlation between my holdings\"* · *\"Calculate the maximum drawdown of my portfolio\"* · "
         "*\"What data is available for SBIN?\"*")

if "chat_history" not in st.session_state:
    st.session_state["chat_history"] = []
for msg in st.session_state["chat_history"]:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])

question = st.chat_input("Ask a financial research question…")
if question:
    st.session_state["chat_history"].append({"role": "user", "content": question})
    ctx = AgentContext(store=store, risk_free_rate=settings.risk_free_rate,
                       trading_days=settings.trading_days_per_year,
                       portfolio_weights=get_portfolio_weights())
    with st.spinner("Running analysis tools…"):
        result = run_agent(question, ctx, settings=settings,
                           history=st.session_state["chat_history"][-6:])
    answer = result["answer"]
    if result.get("tool_used"):
        answer += f"\n\n_Facts above were computed by the `{result['tool_used']}` tool from local data — not generated by the LLM._"
    st.session_state["chat_history"].append({"role": "assistant", "content": answer})
    if result.get("tool_result", {}).get("report_markdown"):
        st.session_state["last_report"] = result["tool_result"]["report_markdown"]
    st.rerun()

if st.session_state.get("last_report"):
    st.download_button("Download last generated report (Markdown)",
                       st.session_state["last_report"], file_name="finsight_report.md", mime="text/markdown")
